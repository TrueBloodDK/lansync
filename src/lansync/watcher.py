"""Coalesced event queue and a single SQLite-owning reconciliation worker."""

import logging
import math
from queue import Empty, Full, Queue
from threading import Event
import time

from watchdog.events import FileSystemEventHandler
from watchdog.observers import Observer

from .manifest import export_manifest
from .scanner import scan_tree, scan_paths
from .storage import Store
from .policy import validate_patterns

LOG = logging.getLogger(__name__)


class ChangeHandler(FileSystemEventHandler):
    def __init__(self, pending):
        self.pending = pending
        self.overflow = Event()

    def on_any_event(self, event):
        # Ignore read/open events generated by our own hashing on Linux.
        if event.event_type not in {"created", "modified", "deleted", "moved", "closed"}:
            return
        # Directory modified notifications accompany child changes; don't
        # recursively rescan the parent for every individual file write.
        if event.event_type == "modified" and getattr(event, "is_directory", False):
            return
        for path in (getattr(event, "src_path", None), getattr(event, "dest_path", None)):
            if not path:
                continue
            try:
                self.pending.put_nowait(path)
            except Full:
                self.overflow.set()


def positive_seconds(value):
    number = float(value)
    if not math.isfinite(number) or number <= 0:
        raise ValueError("Intervals must be finite and greater than zero")
    return number


def watch(root, database, destination, *, debounce=0.5, interval=60.0,
          max_delay=5.0, stop=None, observer_factory=Observer, on_scan=None, exclude_patterns=()):
    """Run until stopped; all database operations stay in the calling thread.

    Events arriving during a scan remain queued for the next pass. Full scans
    also run periodically even without events. Read failures retry then.
    """
    debounce, interval, max_delay = map(positive_seconds, (debounce, interval, max_delay))
    patterns = validate_patterns(exclude_patterns)
    stop = stop if stop is not None else Event()
    pending = Queue(maxsize=4096)
    handler = ChangeHandler(pending)
    observer = observer_factory()
    store = Store(database, root)
    try:
        observer.schedule(handler, str(root), recursive=True)
        observer.start()  # Start before the first scan to cover initialization.

        def reconcile(paths=None):
            result = scan_tree(root, patterns) if paths is None else scan_paths(root, paths, patterns)
            manifest = store.update(result)
            export_manifest(manifest, destination)
            LOG.info("Scan %s: %s objects, %s errors, %s skipped",
                     manifest["generation"], len(result.entries), len(result.errors), len(result.skipped))
            for error in manifest["errors"] + manifest["portability_errors"]:
                LOG.warning("%s: %s", error["path"], error["message"])
            if on_scan is not None:
                on_scan(manifest)

        reconcile()
        next_check = time.monotonic() + interval
        first_event = last_event = None
        changed = set()
        force_full = False
        while not stop.is_set():
            if not observer.is_alive():
                raise OSError("Filesystem observer stopped unexpectedly")
            now = time.monotonic()
            deadline = next_check
            if first_event is not None:
                deadline = min(deadline, last_event + debounce, first_event + max_delay)
            try:
                changed.add(pending.get(timeout=max(0, min(0.1, deadline - now))))
                if len(changed) >= 4096:
                    force_full = True
                    changed.clear()
                now = time.monotonic()
                if first_event is None:
                    first_event = now
                last_event = now
            except Empty:
                pass
            now = time.monotonic()
            due = now >= next_check or (first_event is not None and
                  (now >= last_event + debounce or now >= first_event + max_delay))
            if due and not stop.is_set():
                full = now >= next_check or force_full or handler.overflow.is_set()
                if full:
                    handler.overflow.clear()
                reconcile(None if full else changed)
                changed.clear()
                force_full = False
                first_event = last_event = None
                if full:
                    next_check = time.monotonic() + interval
    finally:
        observer.stop()
        if observer.ident is not None:
            observer.join()
        store.close()
